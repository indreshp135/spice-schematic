// Regenerate examples/*.svg and the demo's example module from examples/*.cir.
// Run with `npm run examples`.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parseSpice, renderToSvgString } from '../dist/index.js';

const dir = new URL('../examples/', import.meta.url).pathname;
const files = readdirSync(dir).filter((n) => n.endsWith('.cir')).sort();

const entries = [];
for (const f of files) {
  const text = readFileSync(join(dir, f), 'utf8');
  writeFileSync(join(dir, f.replace(/\.cir$/, '.svg')), renderToSvgString(text));

  const parsed = parseSpice(text);
  entries.push({
    file: f,
    label: parsed.title ?? f.replace(/\.cir$/, ''),
    parts: parsed.components.length,
    // The distinct element letters an example exercises — derived, so the
    // demo's description of a netlist can never disagree with the netlist.
    letters: [...new Set(parsed.components.map((c) => c.type))].sort(),
    text,
  });
  console.log('wrote', f.replace(/\.cir$/, '.svg'));
}

const module = `// GENERATED by scripts/gen-examples.mjs — do not edit.
// Source of truth is examples/*.cir.

export interface Example {
  file: string;
  label: string;
  parts: number;
  letters: string[];
  text: string;
}

export const EXAMPLES: Example[] = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync(new URL('../example/src/examples.ts', import.meta.url).pathname, module);
console.log(`wrote example/src/examples.ts (${entries.length} examples)`);
